

name=("sanket")
print(len(name))#length of the string
print(name[0])#first character
print(name[1:4])#substring from index 1 to 3
print(name[1:4:2])#substring from index 1 to 3 with step 2
#negative indexing selicing
print(name[-1:-6])#substring from index -1 to -6
print(name[-1:-6:-1])#substring from index -1 to -6 with step -1

#convert negative indexing to positive indexing
print(name[5:0:-1])#substring from index 5 to 0 with step -1

